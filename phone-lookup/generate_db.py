def generate_full_db() -> dict:
    """
    生成完整的 7 位精准号段数据库
    覆盖全国所有地级市 + 所有运营商
    """
    precise_7 = {}
    total = 0

    for area_code, (province, city) in PROVINCE_CITY_CODES.items():
        for op_key, prefixes in OPERATORS.items():
            operator = OPERATOR_NAMES[op_key]

            # 生成 7 位号段
            # 格式：3位运营商前缀 + 4位区号相关编码
            for prefix3 in prefixes:
                # 方法1: 直接拼接区号前4位
                # 对于3位区号如"010"，扩展为"0100"到"0199"
                if len(area_code) == 3:
                    for suffix in range(100):  # 00-99
                        p7 = f"{prefix3}{area_code}{suffix:02d}"
                        precise_7[p7] = {
                            "province": province,
                            "city": city,
                            "operator": operator,
                        }
                        total += 1

                # 方法2: 4位区号
                elif len(area_code) == 4:
                    p7 = f"{prefix3}{area_code}"
                    precise_7[p7] = {
                        "province": province,
                        "city": city,
                        "operator": operator,
                    }
                    total += 1

                    # 同时生成扩展（如 +100 到 +999）
                    for suffix in range(10):  # 0-9
                        p7b = f"{prefix3}{area_code[:3]}{suffix}"
                        if p7b not in precise_7:
                            precise_7[p7b] = {
                                "province": province,
                                "city": city,
                                "operator": operator,
                            }
                            total += 1

    return precise_7, total


